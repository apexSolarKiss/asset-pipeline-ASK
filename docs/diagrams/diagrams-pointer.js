/* diagrams-pointer.js — design-system-ASK shared pointer controller for diagrams (v2, 2026-10-08; v1).

   DS-OWNED SUPPORT FILE. Canonical in patterns/_diagram-shared/; every consuming pattern
   carries a generated byte-identical mirror (tools/sync-diagram-shared.mjs). Do not
   hand-edit a mirror or a vendored copy; edit the canonical and re-emit.

   ONE CONTROLLER FOR MOUSE, PEN AND TOUCH, on Pointer Events.
     one pointer    pans once it travels past the tap slop — 4px for a mouse, 12px for a
                    finger or pen — so a tap still reaches the stage as a click
     two pointers   pinch: the world point under the starting centroid stays under the
                    moving centroid; lifting one finger keeps panning
     moved gesture  swallows the pointer click that follows it, before anything on the stage
                    sees it, so a pan never selects, clears, changes a selection or follows a
                    link; a keyboard or programmatic activation is never swallowed
     wheel          zooms about the pointer, one step per event
   Only a primary-button press starts a gesture: the left mouse button, a pen tip, a finger.
   The middle and right buttons and a pen's barrel stay native, so a link still opens in a
   new tab and the context menu still opens. The stage should carry `touch-action: none`,
   so gestures are handed to this controller on the stage only; panels beside it keep
   native scrolling and taps.

   PANELS INSIDE THE STAGE (v2). A static diagram's canvas is both the drawing region and
   the home of the panels laid over it (caption, legend, HUD, the responsive chrome). Its
   caller names those panels in `exclude`: a press that starts on one stays native and
   starts no gesture, and a wheel over one scrolls it natively unless it carries ctrlKey (a
   trackpad pinch), which still zooms the drawing. An open panel that scrolls keeps its
   native touch scrolling under `touch-action: none` on the stage, because a scroll
   container re-enables panning for itself.

   THE OWNED STAGE IS MARKED. attach() sets `data-diagram-pointer` on the stage, and an aborted
   signal removes it, so a stylesheet can give `touch-action: none` to exactly the drawing this
   controller owns — never to one whose page has not loaded it.

   THE GESTURE SURFACE. With `exclude`, the panels share the stage, so `touch-action: none` cannot
   sit on the stage itself: no descendant can widen an ancestor's touch-action again, and a pinch
   over a panel must still zoom the page. The controller therefore lays a bare, aria-hidden layer
   under everything else in the stage — its first child, filling it, `touch-action: none` — and
   the caller's stylesheet gives the drawing the same; the panels keep the browser's own touch
   behavior, page zoom included, and iOS's own pinch gesture is refused only off the panels.
   Without `exclude` the stage is the gesture surface and carries `touch-action: none` itself.

   The controller owns gesture recognition only. It never reads the diagram, never decides
   what a tap selects, and holds no camera of its own: the caller supplies the view and
   applies every change. Every listener is attached under the caller's AbortSignal, so
   aborting it removes them all.

   DONOR. The gesture logic is a device-approved controller from the first consumer of the
   radial grammar, moved as donor code with two declared corrections:
     a wheel event with deltaY 0 (a horizontal scroll) no longer zooms out; it is ignored
     the pointer that remains after a pinch keeps its own type and slop; it is no longer
       re-typed as touch

   attach({ stage, getView, setView, zoomAt, clampK, signal, wheelStep?, exclude? })
     getView()                      -> { k, x, y }
     setView({ k, x, y }, cause)    cause: 'pan' | 'pinch'
     zoomAt(factor, cx, cy, cause)  cause: 'wheel'; cx, cy in stage coordinates
     clampK(k)                      -> the caller's zoom range
     exclude                        optional selector for the panels inside the stage (above)
   Returns { panning(), gesture() }. VERSION 2 marks `exclude` and the keyboard-safe click
   rule; a caller that needs either checks it and fails closed on an older copy. */
(function (root) {
  'use strict';

  function attach(o) {
    if (!o || !o.stage || typeof o.getView !== 'function' || typeof o.setView !== 'function' ||
        typeof o.zoomAt !== 'function' || typeof o.clampK !== 'function')
      throw new Error('diagrams-pointer: attach needs stage, getView, setView, zoomAt and clampK');
    var stage = o.stage, signal = o.signal, step = o.wheelStep || 1.13, exclude = o.exclude || null;
    function on(target, type, fn, extra) {
      var x = extra ? Object.assign({}, extra) : {};
      if (signal) x.signal = signal;
      target.addEventListener(type, fn, x);
    }
    var pointers = {}, types = {}, gesture = null, swallowClick = false, swallowTimer = null;
    var surface = null;
    if (exclude) {
      surface = document.createElement('div');
      surface.setAttribute('data-diagram-pointer-surface', '');
      surface.setAttribute('aria-hidden', 'true');
      surface.style.cssText = 'position:absolute;top:0;right:0;bottom:0;left:0;touch-action:none';
      stage.insertBefore(surface, stage.firstChild);
    }
    stage.setAttribute('data-diagram-pointer', '');
    if (signal) signal.addEventListener('abort', function () {
      stage.removeAttribute('data-diagram-pointer');
      if (surface && surface.parentNode) surface.parentNode.removeChild(surface);
    });
    /* A press or a wheel that starts on one of the caller's panels stays native. */
    function excluded(e) {
      var t = e.target;
      return !!(exclude && t && t.closest && t.closest(exclude));
    }
    /* The click a moved gesture would leave behind. Only a pointer can produce it: a
       keyboard or programmatic activation dispatches a click with no pointer type and a
       zero click count, and is never swallowed. The token also expires, so a gesture that
       produced no click (a touch pan) cannot wait to eat a later activation; the next
       press, wherever it lands, clears it too. */
    function setSwallow(on) {
      swallowClick = on;
      if (swallowTimer) { clearTimeout(swallowTimer); swallowTimer = null; }
      if (on) swallowTimer = setTimeout(function () { swallowClick = false; swallowTimer = null; }, 500);
    }

    function stagePoint(e) {
      var r = stage.getBoundingClientRect();
      return { x: e.clientX - r.left, y: e.clientY - r.top };
    }
    function activeIds() { return Object.keys(pointers); }
    function slopFor(type) { return type === 'mouse' ? 4 : 12; }
    function markMoved() {
      if (stage.classList.contains('panning')) return;
      stage.classList.add('panning');
      activeIds().forEach(function (id) {
        try { stage.setPointerCapture(+id); } catch (err) { /* pointer already gone */ }
      });
    }
    function beginPan(id, carried) {
      var p = pointers[id], v = o.getView();
      gesture = { kind: 'pan', id: id, x0: p.x, y0: p.y, vx: v.x, vy: v.y,
                  moved: !!carried, slop: slopFor(types[id]) };
    }
    function beginPinch() {
      var ids = activeIds(), a = pointers[ids[0]], b = pointers[ids[1]], v = o.getView();
      var cx = (a.x + b.x) / 2, cy = (a.y + b.y) / 2;
      gesture = { kind: 'pinch', d0: Math.hypot(b.x - a.x, b.y - a.y) || 1, k0: v.k,
                  wx: (cx - v.x) / v.k, wy: (cy - v.y) / v.k, moved: true };
      markMoved();
    }
    function reset() { pointers = {}; types = {}; gesture = null; stage.classList.remove('panning'); }

    on(stage, 'pointerdown', function (e) {
      /* Any press that starts a new pointer sequence retires a click token a finished gesture
         left behind — on a panel or with another button too — so a tap on the HUD or a trigger
         straight after a touch pan is never mistaken for the pan's own click. */
      if (!activeIds().length) setSwallow(false);
      if (e.button !== 0 || excluded(e)) return;
      /* a pointer still on record missed its pointerup (a context menu can swallow one):
         start over rather than pinch against a stale record */
      if (pointers[e.pointerId]) reset();
      var n = activeIds().length;
      if (n >= 2) return;                                // a third finger changes nothing
      if (!n) { setSwallow(false); gesture = null; }
      pointers[e.pointerId] = stagePoint(e);
      types[e.pointerId] = e.pointerType;
      if (!n) beginPan(e.pointerId, false); else beginPinch();
    });
    on(root, 'pointermove', function (e) {
      if (!gesture || !pointers[e.pointerId]) return;
      if (e.pointerType !== 'touch' && e.buttons === 0) { endPointer(e); return; }
      pointers[e.pointerId] = stagePoint(e);
      var v = o.getView();
      if (gesture.kind === 'pan') {
        if (String(e.pointerId) !== String(gesture.id)) return;
        var p = pointers[gesture.id], dx = p.x - gesture.x0, dy = p.y - gesture.y0;
        if (!gesture.moved && Math.abs(dx) + Math.abs(dy) <= gesture.slop) return;
        if (!gesture.moved) { gesture.moved = true; markMoved(); }
        o.setView({ k: v.k, x: gesture.vx + dx, y: gesture.vy + dy }, 'pan');
      } else {
        var ids = activeIds(), a = pointers[ids[0]], b = pointers[ids[1]];
        var nk = o.clampK(gesture.k0 * (Math.hypot(b.x - a.x, b.y - a.y) || 1) / gesture.d0);
        o.setView({ k: nk, x: (a.x + b.x) / 2 - gesture.wx * nk, y: (a.y + b.y) / 2 - gesture.wy * nk }, 'pinch');
      }
    });
    function endPointer(e) {
      if (!pointers[e.pointerId]) return;
      delete pointers[e.pointerId];
      delete types[e.pointerId];
      try { stage.releasePointerCapture(e.pointerId); } catch (err) { /* not captured */ }
      if (gesture && gesture.moved) setSwallow(true);
      var ids = activeIds();
      if (ids.length === 1) beginPan(ids[0], gesture ? gesture.moved : false);
      else if (!ids.length) { gesture = null; stage.classList.remove('panning'); }
    }
    on(root, 'pointerup', endPointer);
    on(root, 'pointercancel', endPointer);
    on(stage, 'click', function (e) {
      if (!swallowClick) return;
      if (!((typeof e.pointerType === 'string' && e.pointerType !== '') || e.detail > 0)) return;
      setSwallow(false); e.stopPropagation(); e.preventDefault();
    }, { capture: true });
    /* iOS Safari delivers its own pinch-to-zoom as gesture events; the stage keeps them, except
       over the caller's panels, which keep the page's zoom */
    on(stage, 'gesturestart', function (e) { if (!excluded(e)) e.preventDefault(); }, { passive: false });
    on(stage, 'wheel', function (e) {
      if (!e.ctrlKey && excluded(e)) return;            // a panel scrolls natively
      e.preventDefault();
      if (!e.deltaY) return;                             // a horizontal scroll does not zoom
      var rect = stage.getBoundingClientRect();
      o.zoomAt(e.deltaY < 0 ? step : 1 / step, e.clientX - rect.left, e.clientY - rect.top, 'wheel');
    }, { passive: false });

    return {
      panning: function () { return stage.classList.contains('panning'); },
      gesture: function () { return gesture ? gesture.kind : null; }
    };
  }

  root.DIAGRAM_POINTER = { attach: attach, VERSION: 2 };
})(typeof window !== 'undefined' ? window : globalThis);
